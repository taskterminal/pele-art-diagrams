// build: put together the site from the projects its pictures come from. Nothing on the page is an image file:
// every plate is drawn in the visitor's browser by the same code that drew it here.
//   node build.mjs                                   (SITE=https://your-site.vercel.app node build.mjs for share links)
// - kit/plates.js: ../fourdiagrams' drawing code (the oav kit, the hand lettering, the sheet and the four plates),
//   bundled as CommonJS modules ahead of plates-worker.js, which runs one in a Worker;
// - data/<plate>.marks.json: pele's layout of each plate (the marks the plate is drawn from);
// - src/<name>.mmd: each plate's Mermaid text, also written into index.html's code blocks; vendor/pele.global.js:
//   pele (MIT), which lays the text out again live on the page;
// - burger/film.html: the burger film (../burger/diagrammed) without its sound, plus burger/sheet-mode.js, which
//   draws the film's twelve figures into one sheet;
// - og.jpg (the share card) and the icons: the only picture files, since a link preview and a browser tab can't
//   run code. With SITE=https://… the share links in index.html are made absolute (x.com needs that).
// Re-run it after a plate is redrawn.
import fs from 'node:fs'; import path from 'node:path'; import { createRequire } from 'node:module'; import { execFileSync } from 'node:child_process';
const HERE = path.dirname(new URL(import.meta.url).pathname), FOUR = path.join(HERE, '../fourdiagrams'), BURGER = path.join(HERE, '../burger/diagrammed');
const require = createRequire(path.join(FOUR, 'package.json'));
const { createCanvas, loadImage } = require('@napi-rs/canvas');
const PLATES = ['d2-wind', 'd3-vesper', 'd4-thunder', 'd5-comet'], short = (p) => p.slice(3);
const write = (rel, data) => { const f = path.join(HERE, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, data); console.log(rel, (Buffer.byteLength(data) / 1024).toFixed(0) + ' KB') };

// the drawing code, as it is, for the Worker
{
  const files = ['lib/oav/index.js', 'lib/oav/util.js', 'lib/oav/paper.js', 'lib/oav/media.js', 'lib/oav/hand.js', 'lib/oav/raster.js', 'lib/oav/shapes.js',
    'lib/letters.js', 'lib/sheet.js', 'lib/hershey.json', 'lib/hershey-fonts.json', ...PLATES.map((p) => `sheets/${p}.js`)];
  let js = `// plates: generated by build.mjs from ../fourdiagrams (edit the drawing there, then rebuild). The oav kit and the\n// sheets are the owner's; the letters are A. V. Hershey's (public domain) by way of hersheytext (MIT).\nconst MODS = {\n`;
  for (const f of files) {
    const src = fs.readFileSync(path.join(FOUR, f), 'utf8');
    js += `${JSON.stringify('/' + f)}: function (module, exports, require, __filename, __dirname) {\n${f.endsWith('.json') ? 'module.exports = ' + JSON.stringify(JSON.parse(src)) + ';' : src}\n},\n`;
  }
  write('kit/plates.js', js + '};\n' + fs.readFileSync(path.join(HERE, 'plates-worker.js'), 'utf8'));
}
// pele's marks for each plate, exactly as the plate was drawn from (rounding them nudges the wind plate's choices)
for (const p of PLATES) write(`data/${p}.marks.json`, fs.readFileSync(path.join(FOUR, 'out', p + '.marks.json'), 'utf8'));
// the Mermaid text, and pele to lay it out on the page
for (const p of PLATES) write(`src/${short(p)}.mmd`, fs.readFileSync(path.join(FOUR, 'diagrams', p + '.mmd'), 'utf8'));
write('vendor/pele.global.js', fs.readFileSync(path.join(FOUR, 'lib/pele/pele.global.js'), 'utf8'));
write('vendor/pele.LICENSE', fs.readFileSync(path.join(FOUR, 'lib/pele/LICENSE'), 'utf8'));
// the burger film, quiet, with its sheet mode
execFileSync('node', [path.join(BURGER, 'build.mjs'), '--out', path.join(HERE, 'burger/film.html'), '--no-sound', '--extra', path.join(HERE, 'burger/sheet-mode.js')], { cwd: BURGER, stdio: 'inherit' });

// the share card: title on the left, the four plates in a square on the right
{
  const c = createCanvas(1200, 630), g = c.getContext('2d'); g.fillStyle = '#fff'; g.fillRect(0, 0, 1200, 630); g.imageSmoothingQuality = 'high';
  const S = 262, GAP = 10, X = 1200 - 48 - 2 * S - GAP, Y = (630 - 2 * S - GAP) / 2;
  for (const [i, p] of PLATES.entries()) g.drawImage(await loadImage(fs.readFileSync(path.join(FOUR, 'out', p + '.png'))), X + (i % 2) * (S + GAP), Y + Math.floor(i / 2) * (S + GAP), S, S);
  const F = JSON.parse(fs.readFileSync(path.join(FOUR, 'lib/hershey-fonts.json'), 'utf8')), TR = .02;
  const wide = (str, face) => [...str].reduce((w, ch) => w + ((F[face][ch] || F[face][' '])[0] + TR), 0) - TR;   // in caps
  const letter = (str, x, y, cap, face, w) => { const H = F[face]; g.strokeStyle = '#1d1a18'; g.lineWidth = w; g.lineCap = g.lineJoin = 'round';
    for (const ch of str) { const gl = H[ch] || H[' ']; for (const st of gl[1]) { g.beginPath(); for (let i = 0; i < st.length; i += 2) g[i ? 'lineTo' : 'moveTo'](x + st[i] * cap, y + st[i + 1] * cap); g.stroke() } x += (gl[0] + TR) * cap } };
  const L0 = 56, room = X - 48 - L0, title = ['Diagrams,', 'drawn by hand'], sub = ['Four made-up worlds,', 'one diagram each.', 'Laid out by pele,', 'drawn in code.'];
  const cap = Math.min(64, room / Math.max(...title.map((t) => wide(t, 'serif')))), sc = Math.min(24, room / Math.max(...sub.map((t) => wide(t, 'italic'))));
  let y = 150; for (const t of title) { letter(t, L0, y, cap, 'serif', cap * .05); y += cap * 1.55 }
  y += sc * .9; for (const [i, t] of sub.entries()) { letter(t, L0 + 2, y, sc, 'italic', 1.6); y += sc * (i === 1 ? 2.3 : 1.75) }
  write('og.jpg', await c.encode('jpeg', 88));
}
// the icons: the bell from the vesper plate, with its sound
{
  const im = await loadImage(fs.readFileSync(path.join(FOUR, 'out', 'd3-vesper.png')));
  for (const [file, n] of [['favicon.png', 64], ['apple-touch-icon.png', 180]]) {
    const c = createCanvas(n, n), g = c.getContext('2d'); g.imageSmoothingQuality = 'high'; g.drawImage(im, 430, 470, 520, 520, 0, 0, n, n);
    write(file, await c.encode('png'));
  }
}

// index.html: the Mermaid text into its code blocks, and absolute share links when SITE is given
{
  const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  let html = fs.readFileSync(path.join(HERE, 'index.html'), 'utf8');
  html = html.replace(/(<code data-src="([a-z]+)">)[\s\S]*?(<\/code>)/g, (_, open, n, close) => open + esc(fs.readFileSync(path.join(HERE, 'src', n + '.mmd'), 'utf8').trimEnd()) + close);
  const site = (process.env.SITE || '').replace(/\/$/, '');
  html = html.replace(/(<meta (?:property|name)="(?:og:image|twitter:image)" content=")[^"]*(")/g, `$1${site ? site + '/' : ''}og.jpg$2`);
  html = html.replace(/(<meta property="og:url" content=")[^"]*(")/, `$1${site ? site + '/' : ''}$2`);
  fs.writeFileSync(path.join(HERE, 'index.html'), html); console.log('index.html' + (site ? ' (share links on ' + site + ')' : ''));
}
